/** Returns all packages for a given industry, sorted by display order. */
export function getPackagesForIndustry(industryId: string): IndustryPackage[] {
  return industryPackages
    .filter((pkg) => pkg.industryId === industryId)
    .sort((a, b) => a.displayOrder - b.displayOrder);
}

/** Returns true if an industry has at least one real package. */
export function industryHasPackages(industryId: string): boolean {
  return industryPackages.some((pkg) => pkg.industryId === industryId);
}

